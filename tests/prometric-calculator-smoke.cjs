const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const source = fs.readFileSync('public/prometric-calculator.js', 'utf8');
const arithmetic = source.slice(source.indexOf('    function press(key)'), source.indexOf('    for (const key'));
const context = vm.createContext({});
vm.runInContext("let value='0', stored=null, operator=null, fresh=true; const output={textContent:'0'};" + arithmetic, context);
function calculate(keys, expected) {
    vm.runInContext(`press('C'); ${JSON.stringify(keys)}.forEach(press);`, context);
    assert.strictEqual(vm.runInContext('output.textContent', context), expected);
}
calculate(['2','+','3','='], '5');
calculate(['9','−','4','='], '5');
calculate(['6','×','7','='], '42');
calculate(['8','÷','2','='], '4');
calculate(['0','.','1','+','0','.','2','='], '0.3');
calculate(['1','÷','0','='], 'Error');
calculate(['1','÷','0','=','4'], '4');
calculate(['5','±','×','2','='], '-10');
calculate(['1','2','⌫'], '1');
calculate(['2','+','×','3','='], '6');
assert(source.includes("exam.classList.contains('active') && !dialog.open"));
assert(source.includes('#quiz-screen.active .exam-calculator-toggle'));
const events={};
const ui={toggle:{addEventListener:(name,handler)=>events[name]=handler},exam:{classList:{contains:name=>name==='active'}},dialog:{open:false,showModal(){this.open=true;}},positionCalculator:()=>{ui.positioned=true;}};
vm.createContext(ui);
vm.runInContext(source.slice(source.indexOf("    toggle.addEventListener('click'"),source.indexOf("    window.addEventListener('resize'")),ui);
events.click();assert(ui.dialog.open,'Calculator opens in a non-simulation exam');assert(ui.positioned);
ui.dialog.open=false;ui.exam.classList.contains=()=>false;events.click();assert(!ui.dialog.open,'Calculator stays closed outside the exam');
assert(source.includes('dialog.showModal()'));
console.log('Calculator arithmetic and availability in all active learner exams passed.');
