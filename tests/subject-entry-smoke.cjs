const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync('public/script.js','utf8');
const context={topics:[],state:{topicProgressMap:{}},window:{currentUnlockedIdx:0}};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('function getSubtopicLearningItemCount('),source.indexOf('function renderCourseOverview(')),context);
const agreement={id:1,subjectId:16,title:'End User Agreement',subtopics:[{contentType:'subtopic',documentationPath:'agreement.pdf'}]};
const pre={id:2,subjectId:16,title:'Pre-Test',subtopics:[{contentType:'pre_test',attemptsUsed:0}]};
const lesson={id:3,subjectId:16,title:'Renal Nursing',subtopics:[{contentType:'subtopic',videoUrl:'video'}]};
context.topics=[lesson,agreement,pre];
assert(context.isPolicyLearningTopic(agreement));assert(context.isPolicyLearningTopic({title:'Policy'}));
assert(context.isPreTestLearningTopic(pre));assert(context.isPreTestLearningTopic({title:'Pre Test'}));
assert(!context.isPolicyLearningTopic(lesson));
assert(context.isLearningItemAccessible(agreement,{sub:agreement.subtopics[0],type:'doc'},0));
assert(!context.isLearningItemAccessible(pre,{sub:pre.subtopics[0],type:'assessment'},0));
assert(!context.isLearningItemAccessible(lesson,{sub:lesson.subtopics[0],type:'video'},0));
context.state.topicProgressMap[1]=1;
assert(context.isLearningItemAccessible(pre,{sub:pre.subtopics[0],type:'assessment'},0));
assert(!context.isLearningItemAccessible(lesson,{sub:lesson.subtopics[0],type:'video'},0));
pre.subtopics[0].attemptsUsed=1;
assert(context.isLearningItemAccessible(lesson,{sub:lesson.subtopics[0],type:'video'},0));
context.topics=[agreement,lesson];context.state.topicProgressMap[1]=0;
assert(!context.isLearningItemAccessible(lesson,{sub:lesson.subtopics[0],type:'video'},0));
context.state.topicProgressMap[1]=1;
assert(context.isLearningItemAccessible(lesson,{sub:lesson.subtopics[0],type:'video'},0));
assert(!context.isLearningItemAccessible(lesson,{sub:lesson.subtopics[0],type:'video'},1));
context.topics=[{...pre,subjectId:17,subtopics:[{contentType:'pre_test',attemptsUsed:0}]}];
assert(context.isLearningItemAccessible(context.topics[0],{sub:context.topics[0].subtopics[0],type:'assessment'},0));
const batchZoom={id:-99,contentType:'zoom_link',isBatchZoom:true};
context.topics=[lesson];context.state.topicProgressMap={};
assert(context.isLearningItemAccessible(lesson,{sub:batchZoom,type:'zoom'},8));
assert.equal(context.getSubtopicLearningItemCount(batchZoom),0);
lesson.subtopics.push(batchZoom);
assert.equal(context.getSubjectLearningProgress(lesson.subjectId).total,1);
context.topics=[agreement,lesson];context.state.topicProgressMap={};
assert(context.isLearningItemAccessible({subjectId:null,isBatchWideZoomTopic:true},{sub:batchZoom,type:'zoom'},9));
console.log('Policy, End User Agreement, Pre-Test gates and non-progress batch Zoom entries behave correctly.');
