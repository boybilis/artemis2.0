const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync('public/script.js','utf8');
const policy={id:1,subjectId:16,title:'Policy',subtopics:[{id:3,contentType:'subtopic',documentationPath:'/agreement.pdf'}]};
const video={id:2,subjectId:17,title:'Videos',subtopics:[{id:4,contentType:'subtopic',videoUrl:'/video'}]};
const c={topics:[policy,video],subjects:[{id:16,policyAcceptanceRequired:true,policyAccepted:false},{id:17}],state:{topicProgressMap:{1:1,2:1},completedTopics:[1,2]}};
vm.createContext(c);vm.runInContext(source.slice(source.indexOf('function getSubtopicLearningItemCount('),source.indexOf('function openSubjectLearningWorkspace(')),c);
assert(c.hasReadSubjectPolicy(16),'The reading stays saved for the agreement prompt');
assert(!c.isTopicContentComplete(policy),'Read-only progress is not official Policy completion');
assert.equal(c.getSubjectLearningProgress(16).completed,0);
assert.equal(c.getSubjectLearningProgress(16).total,1);
assert.equal(c.getSubjectLearningProgress(16).percentage,0);
assert(!c.isSubjectMockExamUnlocked(16));
assert.equal(c.getSubjectLearningProgress(17).percentage,100,'Other subjects retain their existing progress');
c.subjects[0].policyAccepted=true;
assert(c.isTopicContentComplete(policy));assert.equal(c.getSubjectLearningProgress(16).percentage,100);
assert(c.hasCompletedSubjectPolicy(16));
c.subjects[0].policyAccepted=false;
assert.equal(c.getSubjectLearningProgress(16).percentage,0,'Declining / no verification never counts as completed');
console.log('Policy reading stays saved, but subject progress and completion require confirmed acceptance.');
